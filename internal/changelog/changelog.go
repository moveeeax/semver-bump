// Package changelog renders a Keep-a-Changelog-style section from a set of
// Conventional Commits, grouped by type. Pure formatting, no I/O.
package changelog

import (
	"fmt"
	"sort"
	"strings"

	"github.com/moveeeax/semver-bump/internal/conventional"
)

// section groups a title with the commit types it collects, in output order.
type section struct {
	title string
	types []string
}

var sections = []section{
	{"Features", []string{"feat"}},
	{"Bug Fixes", []string{"fix"}},
	{"Performance Improvements", []string{"perf"}},
	{"Reverts", []string{"revert"}},
	{"Code Refactoring", []string{"refactor"}},
	{"Documentation", []string{"docs"}},
}

// Header is the preamble written to the top of a fresh CHANGELOG.md.
const Header = "# Changelog\n\nAll notable changes to this project are documented here.\nThis file is generated by [semver-bump](https://github.com/moveeeax/semver-bump) from Conventional Commits.\n"

// Render returns the markdown section for one release. version should already
// carry its display form (e.g. "1.4.0"); date is an ISO-8601 day.
func Render(version, date string, commits []conventional.Commit) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s - %s\n", version, date)

	if breaking := filterBreaking(commits); len(breaking) > 0 {
		b.WriteString("\n### ⚠ BREAKING CHANGES\n\n")
		for _, c := range breaking {
			b.WriteString(bullet(c))
		}
	}

	for _, s := range sections {
		group := filterTypes(commits, s.types)
		if len(group) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n### %s\n\n", s.title)
		for _, c := range group {
			b.WriteString(bullet(c))
		}
	}

	if b.Len() == len(fmt.Sprintf("## %s - %s\n", version, date)) {
		b.WriteString("\n_No user-facing changes._\n")
	}
	return b.String()
}

// Prepend inserts a rendered section directly beneath the changelog header,
// above any previous releases. A missing or headerless document gets a header.
func Prepend(existing, section string) string {
	existing = strings.TrimRight(existing, "\n")
	section = strings.TrimRight(section, "\n") + "\n"

	if existing == "" {
		return Header + "\n" + section
	}
	if !strings.HasPrefix(existing, "# ") {
		return Header + "\n" + section + "\n" + existing + "\n"
	}
	// Split the leading header block (up to the first blank line after it)
	// from the rest, then insert the new section between them.
	idx := strings.Index(existing, "\n## ")
	if idx == -1 {
		return existing + "\n\n" + section
	}
	head := existing[:idx]
	rest := existing[idx+1:]
	return head + "\n\n" + section + "\n" + rest + "\n"
}

func bullet(c conventional.Commit) string {
	desc := c.Description
	if c.Scope != "" {
		desc = fmt.Sprintf("**%s:** %s", c.Scope, desc)
	}
	if c.Hash != "" {
		return fmt.Sprintf("- %s (%s)\n", desc, c.Hash)
	}
	return fmt.Sprintf("- %s\n", desc)
}

func filterTypes(commits []conventional.Commit, types []string) []conventional.Commit {
	want := make(map[string]bool, len(types))
	for _, t := range types {
		want[t] = true
	}
	var out []conventional.Commit
	for _, c := range commits {
		if want[c.Type] {
			out = append(out, c)
		}
	}
	sortByScope(out)
	return out
}

func filterBreaking(commits []conventional.Commit) []conventional.Commit {
	var out []conventional.Commit
	for _, c := range commits {
		if c.Breaking {
			out = append(out, c)
		}
	}
	sortByScope(out)
	return out
}

func sortByScope(cs []conventional.Commit) {
	sort.SliceStable(cs, func(i, j int) bool {
		if cs[i].Scope != cs[j].Scope {
			return cs[i].Scope < cs[j].Scope
		}
		return cs[i].Description < cs[j].Description
	})
}
